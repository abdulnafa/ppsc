"use strict";

// Build a read-only article index. Questions and answers remain in the canonical bank.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const root = path.resolve(__dirname, "..");
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "data/questions.js"), "utf8"), context);
const bank = context.window.PPSC_QUIZ_DATA;
const order = new Map(bank.questions.map((question, index) => [question.id, index]));
const sections = [
  { id: "foundations", label: "State, language & definitions" },
  { id: "rights", label: "Fundamental rights" },
  { id: "government", label: "Parliament & institutions" },
  { id: "justice", label: "Courts & judiciary" },
  { id: "history", label: "Historical provisions" }
];
const topics = [], usedTopics = new Set(), usedQuestions = new Set();
for (const filename of ["pakistan-articles-foundations.json", "pakistan-articles-institutions.json"]) {
  const source = JSON.parse(fs.readFileSync(path.join(root, "data", filename), "utf8"));
  assert.equal(source.schemaVersion, 1, filename + ": unsupported schema");
  assert(Array.isArray(source.topics) && source.topics.length, filename + ": missing topics");
  for (const topic of source.topics) {
    assert(/^[a-z0-9-]+$/.test(topic.id) && !usedTopics.has(topic.id), "Invalid/duplicate topic " + topic.id);
    usedTopics.add(topic.id);
    assert(sections.some(section => section.id === topic.section), topic.id + ": unknown section");
    for (const field of ["title", "summary"]) {
      assert(typeof topic[field] === "string" && topic[field].trim().length >= 4, topic.id + ": missing " + field);
      assert(!/[\u0600-\u06ff]/.test(topic[field]), topic.id + ": summary/title must use Roman script");
    }
    assert(topic.summary.length <= 1400, topic.id + ": summary too long");
    assert(Array.isArray(topic.articleNumbers) && topic.articleNumbers.length, topic.id + ": missing article numbers");
    assert(topic.articleNumbers.every(number => typeof number === "string" && /^\d+[A-Z]*$/.test(number)), topic.id + ": invalid article number");
    assert.equal(new Set(topic.articleNumbers).size, topic.articleNumbers.length, topic.id + ": duplicate article number");
    assert(Array.isArray(topic.questionIds) && topic.questionIds.length, topic.id + ": missing questions");
    for (const id of topic.questionIds) {
      assert(order.has(id), topic.id + ": unknown canonical MCQ " + id);
      assert(!usedQuestions.has(id), topic.id + ": duplicated MCQ " + id);
      usedQuestions.add(id);
    }
    assert(Array.isArray(topic.references) && topic.references.length, topic.id + ": missing references");
    for (const reference of topic.references) {
      assert(typeof reference.title === "string" && reference.title.trim().length > 3, topic.id + ": missing reference title");
      const url = new URL(reference.url);
      assert(url.protocol === "https:" && !url.username && !url.password, topic.id + ": unsafe source URL");
    }
    if (topic.questionNotes) {
      for (const [id, note] of Object.entries(topic.questionNotes)) {
        assert(topic.questionIds.includes(id) && typeof note === "string" && note.length > 10, topic.id + ": invalid context note");
      }
    }
    topics.push({
      id: topic.id, section: topic.section, title: topic.title.trim(), summary: topic.summary.trim(),
      articleNumbers: [...topic.articleNumbers].sort((a, b) => a.localeCompare(b, "en", { numeric: true })),
      questionIds: [...topic.questionIds].sort((a, b) => order.get(a) - order.get(b)),
      references: topic.references.map(reference => ({ title: reference.title, url: reference.url })),
      ...(topic.questionNotes ? { questionNotes: topic.questionNotes } : {})
    });
  }
}
topics.sort((a, b) => sections.findIndex(section => section.id === a.section) - sections.findIndex(section => section.id === b.section)
  || a.articleNumbers[0].localeCompare(b.articleNumbers[0], "en", { numeric: true }) || a.id.localeCompare(b.id, "en"));
const output = "// Generated by tools/build-pakistan-articles-topics.js; do not edit.\n"
  + "window.PPSC_ARTICLES_TOPICS_DATA = " + JSON.stringify({ schemaVersion: 1, sections, topics }, null, 2) + ";\n";
const target = path.join(root, "data/pakistan-articles-topics.js");
if (process.argv.includes("--check")) {
  assert.equal(fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n"), output, "Regenerate Articles bundle");
} else {
  fs.writeFileSync(target, output);
}
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const controller = fs.readFileSync(path.join(root, "water-topics.js"), "utf8");
const app = fs.readFileSync(path.join(root, "app.js"), "utf8");
const workflow = fs.readFileSync(path.join(root, ".github/workflows/pages.yml"), "utf8");
assert(html.includes('id="articles-topics-card"') && html.includes('id="articles-topics-screen"'), "Missing Articles UI");
assert(controller.includes('data/pakistan-articles-topics.js?') && app.includes('showScreen("articles-topics")'), "Missing Articles loader/navigation");
assert(!/\b(localStorage|sessionStorage|PPSC_CLOUD)\b/.test(controller), "Reference library must not write progress");
assert(workflow.includes("data/pakistan-articles-topics.js") && workflow.includes("build-pakistan-articles-topics.js --check"), "Missing deployment assets/check");
for (const id of ["ADV2E102-U0159-Q043-SRC", "ADV2E102-U0159-Q043-SIM"]) {
  const historical = topics.find(topic => topic.questionIds.includes(id));
  if (historical) assert(/2024/.test(historical.questionNotes?.[id] || ""), id + ": historical court jurisdiction needs visible 2024 context");
}
console.log(JSON.stringify({
  ok: true, topics: topics.length, mcqReferences: usedQuestions.size, canonicalQuestions: bank.questions.length,
  sections: sections.map(section => ({ ...section, topics: topics.filter(topic => topic.section === section.id).length }))
}, null, 2));
