"use strict";

// Generates a small, lazy-loaded index; canonical questions/answers stay in questions.js.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const root = path.resolve(__dirname, "..");
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "data/questions.js"), "utf8"), context);
const bank = context.window.PPSC_QUIZ_DATA;
const questionIds = new Set(bank.questions.map(q => q.id));
const order = new Map(bank.questions.map((q, index) => [q.id, index]));
const sections = [
  { id: "dams", label: "Dams & reservoirs" },
  { id: "rivers", label: "Rivers & water geography" },
  { id: "barrages", label: "Barrages, headworks & canals" },
  { id: "treaties", label: "Water treaties & institutions" }
];
const usedQuestions = new Set();
const usedTopics = new Set();
const topics = [];
for (const filename of ["pakistan-water-dams.json", "pakistan-water-rivers.json"]) {
  const source = JSON.parse(fs.readFileSync(path.join(root, "data", filename), "utf8"));
  assert.equal(source.schemaVersion, 1, filename + ": unsupported schema");
  assert(Array.isArray(source.topics) && source.topics.length, filename + ": no topics");
  for (const topic of source.topics) {
    assert(/^[a-z0-9-]+$/.test(topic.id) && !usedTopics.has(topic.id), "Invalid/duplicate topic " + topic.id);
    usedTopics.add(topic.id);
    assert(sections.some(section => section.id === topic.section), topic.id + ": invalid section");
    for (const field of ["title", "summary"]) {
      assert(typeof topic[field] === "string" && topic[field].trim().length >= 4, topic.id + ": missing " + field);
      assert(!/[\u0600-\u06ff]/.test(topic[field]), topic.id + ": use Roman Urdu for summaries");
    }
    assert(topic.summary.length <= 1000, topic.id + ": summary too long");
    assert(Array.isArray(topic.questionIds) && topic.questionIds.length, topic.id + ": no questions");
    for (const id of topic.questionIds) {
      assert(questionIds.has(id), topic.id + ": unknown MCQ " + id);
      assert(!usedQuestions.has(id), topic.id + ": repeated MCQ reference " + id);
      usedQuestions.add(id);
    }
    assert(Array.isArray(topic.references) && topic.references.length, topic.id + ": no sources");
    for (const reference of topic.references) {
      assert(typeof reference.title === "string" && reference.title.trim().length > 3, topic.id + ": missing reference title");
      const url = new URL(reference.url);
      assert(url.protocol === "https:" && !url.username && !url.password, topic.id + ": invalid source URL");
    }
    if (topic.questionNotes) {
      for (const [id, note] of Object.entries(topic.questionNotes)) {
        assert(topic.questionIds.includes(id) && typeof note === "string" && note.length > 10, topic.id + ": invalid question note " + id);
      }
    }
    topics.push({
      id: topic.id, section: topic.section, title: topic.title.trim(), summary: topic.summary.trim(),
      questionIds: [...topic.questionIds].sort((a, b) => order.get(a) - order.get(b)),
      references: topic.references.map(reference => ({ title: reference.title, url: reference.url })),
      ...(topic.questionNotes ? { questionNotes: topic.questionNotes } : {})
    });
  }
}
topics.sort((a, b) => sections.findIndex(s => s.id === a.section) - sections.findIndex(s => s.id === b.section)
  || a.title.localeCompare(b.title, "en"));
const output = "// Generated by tools/build-pakistan-water-topics.js; do not edit.\n"
  + "window.PPSC_WATER_TOPICS_DATA = " + JSON.stringify({ schemaVersion: 1, sections, topics }, null, 2) + ";\n";
const target = path.join(root, "data/pakistan-water-topics.js");
if (process.argv.includes("--check")) {
  assert.equal(fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n"), output, "Regenerate water topics bundle");
} else {
  fs.writeFileSync(target, output);
}
const html = fs.readFileSync(path.join(root, "index.html"), "utf8");
const controller = fs.readFileSync(path.join(root, "water-topics.js"), "utf8");
const workflow = fs.readFileSync(path.join(root, ".github/workflows/pages.yml"), "utf8");
assert(html.includes('src="water-topics.js?'), "Water controller missing in HTML");
assert(controller.includes('data/pakistan-water-topics.js?'), "Lazy data asset missing");
assert(!/\b(localStorage|sessionStorage|PPSC_CLOUD)\b/.test(controller), "Reference library must not write progress");
assert(workflow.includes("water-topics.js") && workflow.includes("data/pakistan-water-topics.js"), "Missing deployment assets");
console.log(JSON.stringify({
  ok: true, topics: topics.length, mcqReferences: usedQuestions.size, canonicalQuestions: bank.questions.length,
  sections: sections.map(section => ({ ...section, topics: topics.filter(t => t.section === section.id).length }))
}, null, 2));
