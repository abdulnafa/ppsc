"use strict";

// Deterministic read-only reference bundle; never writes the canonical question bank.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const assert = require("node:assert/strict");
const root = path.resolve(__dirname, "..");
const read = file => fs.readFileSync(path.join(root, file), "utf8");
const context = { window: {} };
vm.runInNewContext(read("data/questions.js"), context);
const questionIds = new Set(context.window.PPSC_QUIZ_DATA.questions.map(q => q.id));
const sections = [
  { id: "pakistan", label: "Pakistan — regular prime ministers" },
  { id: "caretakers", label: "Pakistan — caretaker prime ministers" },
  { id: "world", label: "World — selected prime ministers" }
];
const entries = [], sources = [], ids = new Set(), sourceIds = new Set();
let verifiedOn;
function validDate(value) {
  if (typeof value !== "string" || !/^\d{4}(?:-\d{2}(?:-\d{2})?)?$/.test(value)) return false;
  const full = value.length === 4 ? value + "-01-01" : value.length === 7 ? value + "-01" : value;
  const date = new Date(full + "T00:00:00Z");
  return !isNaN(date) && date.toISOString().slice(0, 10) === full;
}
for (const file of ["data/pakistan-prime-ministers.json", "data/world-prime-ministers.json"]) {
  const data = JSON.parse(read(file));
  assert.equal(data.schemaVersion, 1, file + ": schema");
  assert(validDate(data.verifiedOn) && data.verifiedOn.length === 10, file + ": verification date");
  if (verifiedOn) assert.equal(verifiedOn, data.verifiedOn, "Verification dates differ");
  verifiedOn = data.verifiedOn;
  assert(data.entries?.length && data.sources?.length, file + ": empty source");
  for (const source of data.sources) {
    assert(/^[a-z0-9-]+$/.test(source.id) && !sourceIds.has(source.id), "Duplicate/invalid source " + source.id);
    assert(typeof source.title === "string" && source.title.length > 5, "Missing source title");
    const url = new URL(source.url);
    assert(url.protocol === "https:" && !url.username && !url.password, "Unsafe source URL " + source.id);
    sourceIds.add(source.id);
    sources.push(source);
  }
  for (const entry of data.entries) {
    assert(/^[a-z0-9-]+$/.test(entry.id) && !ids.has(entry.id), "Duplicate/invalid person " + entry.id);
    ids.add(entry.id);
    assert(sections.some(section => section.id === entry.section), entry.id + ": section");
    assert.equal(entry.section === "world", file.includes("world-"), entry.id + ": wrong data file");
    if (entry.section !== "world") assert.equal(entry.country, "Pakistan");
    for (const field of ["name", "country", "summary"]) assert(typeof entry[field] === "string" && entry[field].trim().length > 2, entry.id + ": " + field);
    assert(!/[\u0600-\u06ff]/.test(entry.summary), entry.id + ": use Roman Urdu");
    assert(entry.facts?.length && entry.facts.every(fact => typeof fact === "string" && fact.length > 10), entry.id + ": facts");
    assert(entry.tenures?.length, entry.id + ": no tenure");
    let previousEnd = "";
    for (const tenure of entry.tenures) {
      assert(validDate(tenure.start) && tenure.start <= verifiedOn, entry.id + ": invalid/future start");
      assert(tenure.end === null || validDate(tenure.end), entry.id + ": invalid end");
      assert(tenure.end === null || tenure.end >= tenure.start, entry.id + ": reversed tenure");
      assert(tenure.end === null || tenure.end <= verifiedOn, entry.id + ": future end");
      assert(tenure.start >= previousEnd, entry.id + ": unordered/overlapping terms");
      previousEnd = tenure.end || "9999";
    }
    assert(entry.sourceIds?.length && entry.sourceIds.every(id => sourceIds.has(id)), entry.id + ": unknown/missing source");
    const related = entry.questionIds || [];
    assert.equal(new Set(related).size, related.length, entry.id + ": duplicate MCQ reference");
    assert(related.every(id => questionIds.has(id)), entry.id + ": unknown MCQ");
    entries.push(entry);
  }
}
entries.sort((a, b) => sections.findIndex(s => s.id === a.section) - sections.findIndex(s => s.id === b.section)
  || (a.section === "world" ? a.country.localeCompare(b.country, "en") : 0)
  || a.tenures[0].start.localeCompare(b.tenures[0].start) || a.name.localeCompare(b.name, "en"));
assert.equal(entries.filter(entry => entry.section === "pakistan").length, 20, "Pakistan regular PM coverage");
assert.equal(entries.filter(entry => entry.section === "caretakers").length, 8, "Pakistan caretaker PM coverage");
const output = "// Generated by tools/build-prime-ministers.js; do not edit.\nwindow.PPSC_PRIME_MINISTERS_DATA = "
  + JSON.stringify({ schemaVersion: 1, verifiedOn, sections, sources, entries }, null, 2) + ";\n";
const target = path.join(root, "data/prime-ministers.js");
if (process.argv.includes("--check")) assert.equal(read("data/prime-ministers.js").replace(/\r\n/g, "\n"), output, "Regenerate PM bundle");
else fs.writeFileSync(target, output);
const html = read("index.html"), controller = read("prime-ministers.js"), app = read("app.js"), workflow = read(".github/workflows/pages.yml");
assert(html.includes('id="prime-ministers-card"') && html.includes('id="prime-ministers-screen"'), "Missing PM UI");
assert(controller.includes("data/prime-ministers.js?") && app.includes('showScreen("prime-ministers")'), "Missing PM loader/navigation");
assert(!/\b(localStorage|sessionStorage|PPSC_CLOUD)\b/.test(controller), "PM library must not write progress");
assert(workflow.includes("cp prime-ministers.js _site/") && workflow.includes("cp data/prime-ministers.js _site/data/")
  && workflow.includes("build-prime-ministers.js --check"), "Missing PM deployment assets/check");
console.log(JSON.stringify({ ok: true, entries: entries.length, sections: sections.map(section => ({
  ...section, people: entries.filter(entry => entry.section === section.id).length
})), sources: sources.length, canonicalQuestions: questionIds.size }, null, 2));
